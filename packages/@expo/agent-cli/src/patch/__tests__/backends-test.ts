import { resolvedSpecFromYarnLock } from '../backends';

const LOCKFILE = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@expo/image@^2.0.0", "@expo/image@~2.0.1":
  version "2.0.3"
  resolved "https://registry.yarnpkg.com/@expo/image/-/image-2.0.3.tgz#0a1b2c"
  integrity sha512-abc

"@expo/image@^1.0.0":
  version "1.4.0"
  resolved "https://registry.yarnpkg.com/@expo/image/-/image-1.4.0.tgz#3d4e5f"

left-pad@kudo/left-pad#fix:
  version "1.3.0"
  resolved "git+https://github.com/kudo/left-pad.git#0123456789abcdef0123456789abcdef01234567"

lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#679591c5"
`;

describe(resolvedSpecFromYarnLock, () => {
  it.each([
    ['@expo/image', '2.0.3', 'https://registry.yarnpkg.com/@expo/image/-/image-2.0.3.tgz'],
    ['@expo/image', '1.4.0', 'https://registry.yarnpkg.com/@expo/image/-/image-1.4.0.tgz'],
    ['lodash', '4.17.21', 'https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz'],
    // A git dependency keeps its fragment: it is the commit that was installed.
    [
      'left-pad',
      '1.3.0',
      'git+https://github.com/kudo/left-pad.git#0123456789abcdef0123456789abcdef01234567',
    ],
    ['lodash', '4.17.20', null],
    ['image', '2.0.3', null],
  ])('%s@%s → %s', (name, version, expected) => {
    expect(resolvedSpecFromYarnLock(LOCKFILE, name, version)).toBe(expected);
  });
});
